import { chromium } from "playwright-core";
const b = await chromium.launch();
const ctx = await b.newContext({ viewport: { width: 1440, height: 900 } });
await ctx.addInitScript(() => sessionStorage.setItem("arclaw:splash", "1"));
const p = await ctx.newPage();
await p.goto("http://localhost:3210", { waitUntil: "networkidle" });
await p.waitForTimeout(1500);
const shot = async (name, x, y) => { await p.mouse.move(x, y, { steps: 6 }); await p.waitForTimeout(450); await p.screenshot({ path: `shots/cursor-${name}.png`, clip: { x: x - 60, y: y - 60, width: 120, height: 120 } }); };
await shot("dot", 400, 120);
const btn = await p.locator("a.btn-cream").first().boundingBox();
await shot("ring", btn.x + btn.width / 2, btn.y + btn.height / 2);
const fig = await p.locator("[data-cabinet] .claw-fig").boundingBox();
await shot("claw", fig.x + fig.width / 2, fig.y + fig.height / 2);
await p.mouse.down(); await p.waitForTimeout(300);
await p.screenshot({ path: "shots/cursor-grab.png", clip: { x: fig.x + fig.width / 2 - 60, y: fig.y + fig.height / 2 - 60, width: 120, height: 120 } });
await p.mouse.up();
await b.close();
