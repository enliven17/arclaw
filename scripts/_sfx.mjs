import { chromium } from "playwright-core";
const b = await chromium.launch({ args: ["--autoplay-policy=no-user-gesture-required"] });
const ctx = await b.newContext({ viewport: { width: 1440, height: 900 } });
await ctx.addInitScript(() => sessionStorage.setItem("arclaw:splash", "1"));
const p = await ctx.newPage();
const errs = [];
p.on("pageerror", (e) => errs.push(String(e)));
p.on("console", (m) => m.type() === "error" && errs.push(m.text()));
await p.goto("http://localhost:3210", { waitUntil: "networkidle" });
await p.waitForTimeout(1200);
await p.mouse.click(700, 500);
await p.getByRole("button", { name: /Turn sound/ }).click();
await p.waitForTimeout(200);
const pressed1 = await p.getByRole("button", { name: /Turn sound/ }).getAttribute("aria-pressed");
await p.getByRole("button", { name: /Turn sound/ }).click();
await p.waitForTimeout(200);
const pressed2 = await p.getByRole("button", { name: /Turn sound/ }).getAttribute("aria-pressed");
const stored = await p.evaluate(() => localStorage.getItem("arclaw:sound"));
await p.screenshot({ path: "shots/nav-sound.png", clip: { x: 0, y: 0, width: 1440, height: 70 } });
console.log({ pressed1, pressed2, stored, errs });
await b.close();
