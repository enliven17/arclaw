/**
 * Traces "arclaw" from Geist Medium (lib/og/fonts, SIL OFL) at -0.03em tracking into one outline path and writes
 * lib/brand/wordmark.ts. Run once when the wordmark changes: `node brand/wordmark.mjs`. The app, share cards and
 * brand/logo/*.svg all read the generated path, so the wordmark never depends on the font being installed.
 */
import opentype from "opentype.js";
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = join(dirname(fileURLToPath(import.meta.url)), "..");
const buf = readFileSync(join(ROOT, "lib/og/fonts/Geist-Medium.ttf"));
const font = opentype.parse(buf.buffer.slice(buf.byteOffset, buf.byteOffset + buf.byteLength));

const SIZE = 100;
const TRACK = -0.03 * SIZE;
const glyphs = font.stringToGlyphs("arclaw");
const paths = [];
let x = 0;
glyphs.forEach((g, i) => {
  paths.push(g.getPath(x, 0, SIZE));
  x += (g.advanceWidth / font.unitsPerEm) * SIZE + TRACK;
  if (i < glyphs.length - 1) x += (font.getKerningValue(g, glyphs[i + 1]) / font.unitsPerEm) * SIZE;
});

let minX = Infinity;
let minY = Infinity;
let maxX = -Infinity;
let maxY = -Infinity;
for (const p of paths) {
  const b = p.getBoundingBox();
  minX = Math.min(minX, b.x1);
  minY = Math.min(minY, b.y1);
  maxX = Math.max(maxX, b.x2);
  maxY = Math.max(maxY, b.y2);
}
// Baseline sits at y = 0 in font space; keep it so the lockup can align on it.
const baseline = -minY;
const r = (v) => String(Math.round(v * 10) / 10);
const X = (v) => r(v - minX);
const Y = (v) => r(v - minY);
const d = paths
  .flatMap((p) => p.commands)
  .map((c) => {
    if (c.type === "M" || c.type === "L") return `${c.type}${X(c.x)} ${Y(c.y)}`;
    if (c.type === "Q") return `Q${X(c.x1)} ${Y(c.y1)} ${X(c.x)} ${Y(c.y)}`;
    if (c.type === "C") return `C${X(c.x1)} ${Y(c.y1)} ${X(c.x2)} ${Y(c.y2)} ${X(c.x)} ${Y(c.y)}`;
    return "Z";
  })
  .join("");

const out = `/** Generated by brand/wordmark.mjs from Geist Medium (SIL OFL), -0.03em tracking. Do not edit by hand. */
export const WORD_W = ${(maxX - minX).toFixed(1)};
export const WORD_H = ${(maxY - minY).toFixed(1)};
/** Distance from the top of the wordmark box to the baseline. */
export const WORD_BASELINE = ${baseline.toFixed(1)};
export const WORD_PATH = "${d}";
`;
writeFileSync(join(ROOT, "lib/brand/wordmark.ts"), out);
console.log(`wordmark ${(maxX - minX).toFixed(1)} x ${(maxY - minY).toFixed(1)}, ${d.length} chars`);
