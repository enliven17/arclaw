/**
 * Outcome tables, a faithful port of contracts/script/Deploy.s.sol (ArcConfig.buildTable, packOf, checkRules) and of
 * the checks ArclawRules.store runs on chain, so a keeper reprice produces exactly the table the deploy script would
 * for the same prices. Driven by lib/machines.json.
 *
 * Units, never mixed:
 *   price, target, card value   native USDC, 18 dp (bigint wei)
 *   px                          USD per share, 6 dp (what IPriceSource.priceOf returns)
 *   amount                      token units (the .arc tokens have 18 decimals; validate() takes decimals explicitly)
 *
 * Pure: no chain, no I/O. Unit tests compare buildTable with values the Solidity script computed
 * (lib/keeper/__fixtures__/buildTable.sol.json, regenerated by scripts/keeper/fixture.ts).
 */
import raw from "../machines.json";

export type TierCfg = { name: string; multiplierBps: number; weight: number };
export type MachineCfg = { id: number; name: string; priceUsdc: number; capBps: number; rtpMinBps: number; rtpMaxBps: number; tiers: TierCfg[] };
export type MachinesFile = { policy: { floorBps: number; cardsPerBox: number }; machines: MachineCfg[] };

/** Arclaw.OutcomeInput */
export type OutcomeInput = { weight: bigint; tier: number; tokens: readonly [`0x${string}`, `0x${string}`, `0x${string}`]; amounts: readonly [bigint, bigint, bigint] };

/** The on-chain rules of a machine (Arclaw.machines(id)). */
export type MachineRules = { price: bigint; floorBps: number; capBps: number; rtpMinBps: number; rtpMaxBps: number };

/** Deploy.s.sol symbols(): the order every token and price array follows. */
export const SYMBOLS = ["NVDA", "TSLA", "AAPL", "AMZN", "META", "GOOGL", "SPY", "QQQ"] as const;
export type Symbol8 = (typeof SYMBOLS)[number];

/** Mirrors of Arclaw / Deploy.s.sol constants. */
export const MAX_RTP_BPS = 9500n;
export const MAX_PRICE_MOVE_BPS = 500n;
export const EDGE_MARGIN_BPS = 100n;
export const FLOOR_MARGIN_BPS = 530n;
export const MAX_OUTCOMES = 64;
export const WEI = 10n ** 18n;

export const MACHINES_FILE = raw as MachinesFile;

/** Deploy.s.sol packOf: stock indices into SYMBOLS and the % split of the pack value. */
export function packOf(tier: number): { s: readonly [number, number, number]; pct: readonly [bigint, bigint, bigint] } {
  if (tier === 0) return { s: [6, 7, 2], pct: [40n, 30n, 30n] }; // SPY QQQ AAPL
  if (tier === 1) return { s: [3, 5, 6], pct: [40n, 30n, 30n] }; // AMZN GOOGL SPY
  if (tier === 2) return { s: [2, 4, 7], pct: [40n, 30n, 30n] }; // AAPL META QQQ
  if (tier === 3) return { s: [1, 3, 5], pct: [50n, 25n, 25n] }; // TSLA AMZN GOOGL
  if (tier === 4) return { s: [4, 0, 2], pct: [50n, 30n, 20n] }; // META NVDA AAPL
  return { s: [0, 1, 4], pct: [50n, 30n, 20n] }; // NVDA TSLA META
}

const big = (n: number, what: string): bigint => {
  if (!Number.isSafeInteger(n) || n < 0) throw new Error(`${what} must be a non-negative integer, got ${n}`);
  return BigInt(n);
};

/** Deploy.s.sol checkRules: setMachine's bounds for the machine's band. Throws with the script's reason. */
export function checkRules(m: MachineCfg, floorBps: number): void {
  if (!(floorBps >= 5000 && floorBps <= m.rtpMinBps)) throw new Error("floor must be in [5000, rtpMin]");
  if (!(m.rtpMinBps < m.rtpMaxBps)) throw new Error("rtpMin must be under rtpMax");
  if (!(m.rtpMaxBps <= m.capBps)) throw new Error("rtpMax above cap");
  if (!(BigInt(m.rtpMaxBps) * (10_000n + MAX_PRICE_MOVE_BPS) <= MAX_RTP_BPS * 10_000n)) throw new Error("rtpMax x 1.05 above MAX_RTP_BPS");
}

/**
 * Deploy.s.sol buildTable: one outcome per tier, a 3-card pack worth multiplier x price. A tier under floor x 1.053 is
 * lifted to it, a tier at (or over) the cap is built 1% under it. Amounts round up, except at the cap (down).
 * `tok` and `px` follow SYMBOLS order; px is USD 6 dp.
 */
export function buildTable(m: MachineCfg, floorBps: number, tok: readonly `0x${string}`[], px: readonly bigint[]): OutcomeInput[] {
  if (tok.length !== 8 || px.length !== 8) throw new Error("buildTable needs 8 tokens and 8 prices");
  if (px.some((p) => p <= 0n)) throw new Error("buildTable: every price must be positive");
  const price = big(m.priceUsdc, "priceUsdc") * WEI;
  const cap = big(m.capBps, "capBps");
  const lifted = (big(floorBps, "floorBps") * (10_000n + FLOOR_MARGIN_BPS)) / 10_000n;
  return m.tiers.map((tier, k) => {
    const tm = big(tier.multiplierBps, "multiplierBps");
    const atCap = tm >= cap;
    const mult = atCap ? (cap * (10_000n - EDGE_MARGIN_BPS)) / 10_000n : tm < lifted ? lifted : tm;
    const target = (price * mult) / 10_000n; // USDC 18 dp
    const { s, pct } = packOf(k);
    let left = target;
    const tokens: `0x${string}`[] = [];
    const amounts: bigint[] = [];
    for (let c = 0; c < 3; c++) {
      const v = c === 2 ? left : (target * pct[c]!) / 100n;
      left -= v;
      const p = px[s[c]!]!;
      // value = amount * p * 1e12 / 1e18  =>  amount = value * 1e6 / p
      const amount = atCap ? (v * 1_000_000n) / p : (v * 1_000_000n + p - 1n) / p;
      tokens.push(tok[s[c]!]!);
      amounts.push(amount);
    }
    return {
      weight: big(tier.weight, "weight"),
      tier: k,
      tokens: tokens as unknown as OutcomeInput["tokens"],
      amounts: amounts as unknown as OutcomeInput["amounts"],
    };
  });
}

export type TableCheck = { ok: true; rtpBps: bigint; luckyRtpBps: bigint; minBps: bigint; maxBps: bigint } | { ok: false; reason: string };

/**
 * The checks ArclawRules.store runs at setPrizes, at the prices given: every pack within [floor, cap], weighted EV
 * at least rtpMin and the max-boost EV at most rtpMax. `priceOf` maps a token to its USD 6 dp price, `decimalsOf`
 * to its decimals. Run before signing so a reprice that would revert is never sent.
 */
export function validate(
  input: readonly OutcomeInput[],
  rules: MachineRules,
  priceOf: (token: string) => bigint,
  decimalsOf: (token: string) => number,
  maxBoostBps = 100n,
): TableCheck {
  if (input.length === 0) return { ok: false, reason: "NoPrizes" };
  if (input.length > MAX_OUTCOMES) return { ok: false, reason: "TooManyOutcomes" };
  const price = rules.price;
  const vs: bigint[] = [];
  let w = 0n;
  let ev = 0n;
  let minBps = -1n;
  let maxBps = 0n;
  for (let i = 0; i < input.length; i++) {
    const p = input[i]!;
    if (p.weight <= 0n) return { ok: false, reason: `BadPrize(${i}) zero weight` };
    let v = 0n;
    for (let c = 0; c < 3; c++) {
      const tok = p.tokens[c]!;
      const amt = p.amounts[c]!;
      if (/^0x0{40}$/i.test(tok) || tok.toLowerCase() === "0x3600000000000000000000000000000000000000" || amt === 0n) return { ok: false, reason: `BadPrize(${i})` };
      const px = priceOf(tok);
      if (px <= 0n) return { ok: false, reason: `BadPrize(${i}) unpriced` };
      v += (amt * px * 10n ** 12n) / 10n ** BigInt(decimalsOf(tok));
    }
    if (v * 10_000n < BigInt(rules.floorBps) * price) return { ok: false, reason: `BelowFloor(${i}, ${(v * 10_000n) / price})` };
    if (v * 10_000n > BigInt(rules.capBps) * price) return { ok: false, reason: `AboveCap(${i}, ${(v * 10_000n) / price})` };
    const bps = (v * 10_000n) / price;
    if (minBps < 0n || bps < minBps) minBps = bps;
    if (bps > maxBps) maxBps = bps;
    vs.push(v);
    w += p.weight;
    ev += v * p.weight;
  }
  const rtpBps = (ev * 10_000n) / w / price;
  if (ev * 10_000n < BigInt(rules.rtpMinBps) * price * w) return { ok: false, reason: `RtpOutOfBand(${rtpBps}) under rtpMin ${rules.rtpMinBps}` };
  let pairs = 0n;
  for (let i = 0; i < vs.length; i++) {
    for (let j = 0; j < vs.length; j++) pairs += input[i]!.weight * input[j]!.weight * (vs[i]! > vs[j]! ? vs[i]! : vs[j]!);
  }
  const lucky = (10_000n - maxBoostBps) * ev * w + maxBoostBps * pairs;
  const luckyRtpBps = lucky / w / w / price;
  if (lucky > BigInt(rules.rtpMaxBps) * price * w * w) return { ok: false, reason: `RtpOutOfBand(${luckyRtpBps}) over rtpMax ${rules.rtpMaxBps}` };
  return { ok: true, rtpBps, luckyRtpBps, minBps, maxBps };
}

/** A card of a table as Arclaw.outcomes() returns it. */
export type ChainCard = { token: `0x${string}`; value: bigint; amount: bigint };
export type ChainOutcome = { weight: bigint; tier: number; value: bigint; cards: readonly ChainCard[] };

/**
 * The reference price (USD 6 dp) each token of a live table was set at, recovered from its cards:
 * value = amount * px * 1e12 / 10^dec  =>  px ~ value * 10^dec / (amount * 1e12). The contract keeps the exact
 * reference private; this is within one unit of 6 dp for any realistic card, plenty for a move trigger.
 */
export function refPrices(outcomes: readonly ChainOutcome[], decimalsOf: (token: string) => number): Map<string, bigint> {
  const best = new Map<string, { amount: bigint; px: bigint }>();
  for (const o of outcomes) {
    for (const c of o.cards) {
      if (c.amount === 0n) continue;
      const key = c.token.toLowerCase();
      // ceil: value was floored on chain, so the floor of the inverse would read low
      const num = c.value * 10n ** BigInt(decimalsOf(c.token));
      const den = c.amount * 10n ** 12n;
      const px = (num + den - 1n) / den;
      // the largest card gives the tightest estimate
      const prev = best.get(key);
      if (!prev || c.amount > prev.amount) best.set(key, { amount: c.amount, px });
    }
  }
  return new Map([...best].map(([k, v]) => [k, v.px]));
}

/** |live - ref| / ref in bps (rounded up), the measure ArclawRules.check compares against maxPriceMoveBps. */
export function moveBps(live: bigint, ref: bigint): bigint {
  if (ref <= 0n) return 10_000n;
  const d = live > ref ? live - ref : ref - live;
  return (d * 10_000n + ref - 1n) / ref;
}

/** Two tables are the same (weights, tiers, tokens and amounts): a reprice would change nothing. */
export function sameTable(a: readonly OutcomeInput[], b: readonly ChainOutcome[]): boolean {
  if (a.length !== b.length) return false;
  return a.every((o, i) => {
    const c = b[i]!;
    if (o.weight !== c.weight || o.tier !== c.tier) return false;
    return o.tokens.every((t, k) => t.toLowerCase() === c.cards[k]!.token.toLowerCase() && o.amounts[k] === c.cards[k]!.amount);
  });
}
